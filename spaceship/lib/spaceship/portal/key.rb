      def self.create(name: nil, apns: nil, device_check: nil, music_id: nil)
        service_config = {}

        if apns
          service_config[APNS_ID] = {
            scope: 'team',
            environment: 'all',
            identifiers: {}
          }
        end

        if device_check
          service_config[DEVICE_CHECK_ID] = {
            identifiers: {}
          }
        end

        if music_id
          service_config[MUSIC_KIT_ID] = {
            identifiers: {
              music: [music_id]
            }
          }
        end

